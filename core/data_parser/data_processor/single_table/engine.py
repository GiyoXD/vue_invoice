import decimal
from collections import defaultdict
from typing import List, Dict, Any, Optional
from .schema import DECIMAL_COLUMNS, INTEGER_COLUMNS, TEXT_COLUMNS

__all__ = ["Aggregator", "coerce_input_row"]


def _to_decimal(val: Any) -> decimal.Decimal:
    if val is True or val is False:
        return decimal.Decimal(0)
    try:
        d = decimal.Decimal(str(val).replace(",", "").strip())
        return decimal.Decimal(0) if (d.is_nan() or d.is_infinite()) else d
    except Exception:
        return decimal.Decimal(0)


def _to_integer(val: Any) -> int:
    if val is True or val is False:
        return 0
    try:
        return int(float(str(val).replace(",", "").strip()))
    except Exception:
        return 0


def _to_text(val: Any) -> str:
    return str(val).strip() if val is not None else ""


def coerce_input_row(row: Any) -> Dict[str, Any]:
    try:
        coerced = dict(row)
    except Exception:
        return {}
    for col in DECIMAL_COLUMNS:
        val = coerced.get(col)
        if val is not None:
            coerced[col] = _to_decimal(val)
    for col in INTEGER_COLUMNS:
        val = coerced.get(col)
        if val is not None:
            coerced[col] = _to_integer(val)
    for col in TEXT_COLUMNS:
        val = coerced.get(col)
        if val is not None:
            coerced[col] = _to_text(val)
    return coerced


class Aggregator:
    """
    Generic, declarative data aggregator that groups rows by a key generated by
    key_selector and applies column-specific reduction strategies.
    """
    def __init__(self, key_selector, reducers):
        self.key_selector = key_selector
        self.reducers = reducers

    def aggregate(
        self,
        rows: List[Dict[str, Any]],
        target_map: Optional[Dict[Any, Dict[str, Any]]] = None
    ) -> Dict[Any, Dict[str, Any]]:
        """
        Reduce rows into target_map.

        Each entry in self.reducers can be a callable or a (in_col: str, reducer_fn: callable) tuple.
        """
        if target_map is None:
            target_map = {}

        grouped_rows: Dict[Any, list] = defaultdict(list)
        for row in rows:
            if not row:
                continue
            key = self.key_selector(row)
            if key is not None:
                grouped_rows[key].append(row)

        for key, group in grouped_rows.items():
            if key not in target_map:
                target_map[key] = {}

            for out_col, reducer_config in self.reducers.items():
                if callable(reducer_config):
                    in_col = out_col
                    reducer_fn = reducer_config
                else:
                    try:
                        in_col, reducer_fn = reducer_config
                    except Exception:
                        raise TypeError(f"Invalid reducer config for '{out_col}': {reducer_config}")
                existing_val = target_map[key].get(out_col)
                col_values = [row.get(in_col) for row in group if row.get(in_col) is not None]
                if existing_val is not None:
                    col_values.insert(0, existing_val)

                reduced_val = reducer_fn(col_values)
                if reduced_val is not None:
                    target_map[key][out_col] = reduced_val

        return target_map
